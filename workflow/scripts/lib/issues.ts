// Pure GitHub-issue rendering for PLAN.md tasks; the CLI performs all gh calls.
import { taskAnchor, taskCriteria, taskDependencies, taskOwner, taskStatus, type PlanTask } from "./plan";

export const roleLabels: Record<string, { color: string; description: string }> = {
  testing: { color: "1d76db", description: "Testing-agent task from workflow/PLAN.md" },
  implementation: { color: "0e8a16", description: "Implementation-agent task from workflow/PLAN.md" },
  spec: { color: "5319e7", description: "Spec-agent task from workflow/PLAN.md" },
};

export interface PlannedIssue {
  taskId: string;
  title: string;
  body: string;
  labels: string[];
  milestone: string;
}

/** Only `Issue: unassigned` tasks need one; others are mapped or, like spec tasks, have none. */
export function needsIssue(task: PlanTask): boolean {
  return !task.removed && /^\s*unassigned\s*$/.test(task.fields.get("Issue") ?? "");
}

export function issueTitle(task: PlanTask): string {
  return `${task.id}: ${task.title}`;
}

/** Existing issues are matched by task-ID prefix so a retitled issue is not duplicated. */
export function existingIssueNumbers(tasks: PlanTask[], issues: { number: number; title: string }[]) {
  const numbers = new Map<string, number>();
  for (const task of tasks) {
    const match = issues.find((issue) => issue.title.startsWith(`${task.id}:`));
    if (match) numbers.set(task.id, match.number);
  }
  return numbers;
}

/** Testing and implementation tasks for the same criteria share one branch and PR. */
export function pairedTasks(task: PlanTask, tasks: PlanTask[]): string[] {
  if (task.removed) return [];
  const owner = taskOwner(task);
  const criteria = new Set(taskCriteria(task));
  const matching = tasks.filter((other) => {
    const otherCriteria = taskCriteria(other);
    return !other.removed && otherCriteria.length === criteria.size && otherCriteria.every((id) => criteria.has(id));
  });
  if (owner === "implementation") {
    return taskDependencies(task).filter((id) => matching.some((other) => other.id === id && taskOwner(other) === "testing"));
  }
  if (owner === "testing") {
    return matching
      .filter((other) => taskOwner(other) === "implementation" && taskDependencies(other).includes(task.id))
      .map((other) => other.id);
  }
  return [];
}

export function planIssue(
  task: PlanTask,
  tasks: PlanTask[],
  options: { repoUrl: string; branch: string; issueNumbers: Map<string, number> },
): PlannedIssue {
  const planUrl = `${options.repoUrl}/blob/${options.branch}/workflow/PLAN.md`;
  const field = (name: string) => absoluteLinks(dedent(task.fields.get(name) ?? ""), planUrl);
  const reference = (id: string) => {
    const number = options.issueNumbers.get(id);
    return number ? `${id} (#${number})` : `${id} (issue not created yet)`;
  };
  const dependencies = taskDependencies(task);
  const pairs = pairedTasks(task, tasks);
  const sections = [
    "<!-- Generated by workflow/scripts/create-issues.ts from workflow/PLAN.md.",
    "PLAN.md and its linked specs are authoritative. Change them through a spec PR;",
    "do not edit requirements or acceptance criteria in this issue. -->",
    "",
    `**Plan task:** [${task.id}](${planUrl}#${taskAnchor(task)})`,
    `**Owner role:** ${taskOwner(task)}`,
    `**Status in PLAN.md at creation:** ${taskStatus(task)}`,
    `**Depends on:** ${dependencies.length ? dependencies.map(reference).join(", ") : "None"}`,
    `**Requirements:** ${field("Requirements")}`,
    "",
    "## Description",
    "",
    field("Description"),
    "",
    "## Work",
    "",
    field("Work"),
    "",
    "## File scope",
    "",
    field("File scope"),
  ];
  if (task.fields.has("Prerequisite")) sections.push("", "## Prerequisite", "", field("Prerequisite"));
  sections.push(
    "",
    "## Acceptance criteria",
    "",
    field("Acceptance criteria"),
    "",
    "## Workflow",
    "",
    "- Branch `<type>/<issue>-<slug>`; agent reports go in `workflow/handoffs/<issue>-<slug>/`.",
    pairs.length
      ? `- Shares one branch and one PR with ${pairs.map(reference).join(", ")}; the testing task runs first, and the branch, handoff folder and PR are named after its issue. The PR closes both issues.`
      : "- No paired testing/implementation task.",
    "- Follow `.agents/skills/sdd-orchestrate/SKILL.md` for the gates between agents.",
  );
  return {
    taskId: task.id,
    title: issueTitle(task),
    body: `${sections.join("\n")}\n`,
    labels: roleLabels[taskOwner(task)] ? [taskOwner(task)] : [],
    milestone: task.section,
  };
}

/** Replace `- **Issue:** unassigned` for one task with a link; other text is untouched. */
export function setPlanIssue(plan: string, taskId: string, number: number, repoUrl: string): string {
  const lines = plan.split("\n");
  const start = lines.findIndex((line) => line.startsWith(`### ${taskId}:`));
  if (start < 0) return plan;
  for (let index = start + 1; index < lines.length && !/^#{1,3} /.test(lines[index]); index++) {
    if (/^- \*\*Issue:\*\*\s*unassigned\s*$/.test(lines[index])) {
      lines[index] = `- **Issue:** [#${number}](${repoUrl}/issues/${number})`;
      break;
    }
  }
  return lines.join("\n");
}

function dedent(text: string): string {
  const lines = text.split("\n");
  const indents = lines.slice(1).filter((line) => line.trim()).map((line) => line.match(/^ */)![0].length);
  const indent = indents.length ? Math.min(...indents) : 0;
  return [lines[0], ...lines.slice(1).map((line) => line.slice(indent))].join("\n").trim();
}

function absoluteLinks(text: string, planUrl: string): string {
  return text.replace(/\]\(([^)\s]+)\)/g, (link, target: string) =>
    /^[a-z][a-z0-9+.-]*:/i.test(target) ? link : `](${new URL(target, planUrl).href})`,
  );
}
